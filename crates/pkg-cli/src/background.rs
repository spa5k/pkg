//! Per-user periodic job that updates pkg and official discovery metadata.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::config::Paths;

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("{0}")]
    Message(String),
    #[error("{0}")]
    Io(#[from] std::io::Error),
    #[error("{0}")]
    Publish(#[from] tempfile::PersistError),
    #[error("{0}")]
    Process(#[from] pkg_process::RunError),
    #[error("{program} was cancelled by signal {signal}")]
    Interrupted { program: String, signal: i32 },
    #[error("job files exist, but the schedule is not active: {0}. Run `pkg background enable`.")]
    Schedule(#[source] Box<Self>),
    #[error("daily updates need a systemd user session, and this system has none. {MANUAL}")]
    NoScheduler,
}

/// What to do on a system that cannot run the daily job.
const MANUAL: &str = "Run `pkg update` to update by hand.";

impl From<String> for Error {
    fn from(message: String) -> Self {
        Self::Message(message)
    }
}

impl From<&str> for Error {
    fn from(message: &str) -> Self {
        Self::Message(message.to_string())
    }
}

impl Error {
    pub fn signal(&self) -> Option<i32> {
        match self {
            Self::Process(error) => error.cancelled,
            Self::Interrupted { signal, .. } => Some(*signal),
            Self::Schedule(error) => error.signal(),
            Self::Message(_) | Self::Io(_) | Self::Publish(_) | Self::NoScheduler => None,
        }
    }
}

const LABEL: &str = "com.pkg.catalog-refresh";
const MARKER: &str = "Generated by pkg; catalog refresh only.";

struct Job {
    files: Vec<(PathBuf, String)>,
    log: PathBuf,
}

fn text(path: &Path) -> Result<&str, Error> {
    let value = path.to_str().ok_or("job paths must be UTF-8")?;
    if value.chars().any(char::is_control) {
        return Err("job paths must not contain control characters".into());
    }
    Ok(value)
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn unit(value: &str, exec: bool) -> String {
    let value = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    format!(
        "\"{}\"",
        if exec {
            value.replace('$', "$$")
        } else {
            value
        }
    )
}

fn user_home() -> Result<PathBuf, Error> {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .ok_or_else(|| Error::from("HOME must be absolute for background setup"))
}

fn job(
    paths: &Paths,
    home: &Path,
    executable: &Path,
    nix: &Path,
    macos: bool,
) -> Result<Job, Error> {
    let executable = text(executable)?;
    let state = text(&paths.state_home)?;
    let config_base = paths
        .config_file
        .parent()
        .and_then(Path::parent)
        .ok_or("config base is missing")?;
    let config = text(config_base)?;
    let cache_base = paths.cache_dir.parent().ok_or("cache base is missing")?;
    let cache = text(cache_base)?;
    let home_text = text(home)?;
    let nix_bin = text(nix.parent().ok_or("Nix executable has no parent")?)?;
    let inherited_path = std::env::var("PATH").unwrap_or_default();
    if inherited_path.chars().any(char::is_control) {
        return Err("PATH must not contain control characters for background setup".into());
    }
    let path = format!("{nix_bin}:{inherited_path}:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin");
    let log = paths.state_home.join("pkg/catalog-refresh.log");
    let log_text = text(&log)?;
    let environment = [
        ("HOME", home_text),
        ("XDG_STATE_HOME", state),
        ("XDG_CONFIG_HOME", config),
        ("XDG_CACHE_HOME", cache),
        ("PATH", path.as_str()),
    ];
    let files = if macos {
        let mut env = String::new();
        for (key, value) in &environment {
            let _ = write!(env, "<key>{key}</key><string>{}</string>", xml(value));
        }
        let content = format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<!-- {MARKER} -->\n<plist version=\"1.0\"><dict>\n<key>Label</key><string>{LABEL}</string>\n<key>ProgramArguments</key><array><string>{}</string><string>update</string><string>--scheduled</string></array>\n<key>EnvironmentVariables</key><dict>{env}</dict>\n<key>StartInterval</key><integer>86400</integer>\n<key>ProcessType</key><string>Background</string>\n<key>Nice</key><integer>10</integer>\n<key>LowPriorityIO</key><true/>\n<key>StandardInPath</key><string>/dev/null</string>\n<key>StandardOutPath</key><string>{}</string>\n<key>StandardErrorPath</key><string>{}</string>\n</dict></plist>\n",
            xml(executable),
            xml(log_text),
            xml(log_text)
        );
        vec![(
            home.join(format!("Library/LaunchAgents/{LABEL}.plist")),
            content,
        )]
    } else {
        let mut env = String::new();
        for (key, value) in &environment {
            let _ = writeln!(
                env,
                "Environment={}",
                unit(&format!("{key}={value}"), false)
            );
        }
        let service = format!(
            "# {MARKER}\n[Unit]\nDescription=Update pkg and its package catalogs\n[Service]\nType=oneshot\nExecStart={} update --scheduled\n{env}StandardInput=null\nNice=10\nTimeoutStartSec=30min\n",
            unit(executable, true)
        );
        let timer = format!(
            "# {MARKER}\n[Unit]\nDescription=Daily pkg update\n[Timer]\nOnStartupSec=10min\nOnUnitInactiveSec=1d\nRandomizedDelaySec=10min\n[Install]\nWantedBy=timers.target\n"
        );
        let directory = config_base.join("systemd/user");
        vec![
            (directory.join("pkg-catalog-refresh.service"), service),
            (directory.join("pkg-catalog-refresh.timer"), timer),
        ]
    };
    Ok(Job { files, log })
}

fn owned(path: &Path) -> Result<bool, Error> {
    match std::fs::symlink_metadata(path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error.into()),
        Ok(metadata) if metadata.is_file() && !metadata.file_type().is_symlink() => {
            let content = std::fs::read_to_string(path)?;
            if content.contains(MARKER) {
                Ok(true)
            } else {
                Err(format!(
                    "refusing to replace a job file not owned by pkg: {}",
                    path.display()
                )
                .into())
            }
        }
        Ok(_) => Err(format!("unsafe job file: {}", path.display()).into()),
    }
}

fn write(path: &Path, content: &str) -> Result<(), Error> {
    use std::io::Write as _;
    let directory = path.parent().ok_or("job directory is missing")?;
    std::fs::create_dir_all(directory)?;
    let mut file = tempfile::NamedTempFile::new_in(directory)?;
    file.write_all(content.as_bytes())
        .and_then(|()| file.as_file().sync_all())?;
    file.persist(path)?;
    Ok(())
}

fn control(program: &str, args: &[&str]) -> Result<(), Error> {
    match crate::nix::run_direct(Path::new(program), args)? {
        crate::nix::Outcome::Success => Ok(()),
        crate::nix::Outcome::Failed { status, stderr } => {
            Err(format!("{program} {}: {status}: {}", args.join(" "), stderr.trim()).into())
        }
        crate::nix::Outcome::Interrupted { signal } => Err(Error::Interrupted {
            program: program.to_string(),
            signal,
        }),
    }
}

fn optional_control(program: &str, args: &[&str]) -> Result<(), Error> {
    match control(program, args) {
        Err(error) if error.signal().is_none() => Ok(()),
        result => result,
    }
}

fn domain() -> String {
    // SAFETY: geteuid has no arguments or memory effects.
    format!("gui/{}", unsafe { libc::geteuid() })
}

/// Whether the system can run the job. Linux needs a running systemd user
/// manager; containers, WSL, and some SSH sessions have none.
fn scheduler_ready() -> Result<bool, Error> {
    if cfg!(target_os = "macos") {
        return Ok(true);
    }
    match crate::nix::run_direct(Path::new("systemctl"), &["--user", "show-environment"]) {
        Ok(crate::nix::Outcome::Success) => Ok(true),
        Ok(crate::nix::Outcome::Interrupted { signal }) => Err(Error::Interrupted {
            program: String::from("systemctl"),
            signal,
        }),
        Err(error) if error.cancelled.is_some() => Err(error.into()),
        // No user manager runs, or systemctl is not installed.
        Ok(crate::nix::Outcome::Failed { .. }) | Err(_) => Ok(false),
    }
}

pub fn enable(paths: &Paths, nix: &Path) -> Result<(), Error> {
    if !scheduler_ready()? {
        return Err(Error::NoScheduler);
    }
    let executable = std::env::current_exe()?;
    let job = job(
        paths,
        &user_home()?,
        &executable,
        nix,
        cfg!(target_os = "macos"),
    )?;
    for (path, _) in &job.files {
        owned(path)?;
    }
    for (path, content) in &job.files {
        write(path, content)?;
    }
    if cfg!(target_os = "macos") {
        if let Some(parent) = job.log.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let target = format!("{}/{LABEL}", domain());
        optional_control("/bin/launchctl", &["bootout", &target])?;
        control("/bin/launchctl", &["enable", &target])?;
        control(
            "/bin/launchctl",
            &["bootstrap", &domain(), text(&job.files[0].0)?],
        )?;
        // Run once now, so search data is ready soon after installation.
        optional_control("/bin/launchctl", &["kickstart", &target])?;
    } else {
        control("systemctl", &["--user", "daemon-reload"])?;
        control(
            "systemctl",
            &["--user", "enable", "--now", "pkg-catalog-refresh.timer"],
        )?;
        optional_control(
            "systemctl",
            &[
                "--user",
                "start",
                "--no-block",
                "pkg-catalog-refresh.service",
            ],
        )?;
    }
    Ok(())
}

fn configured_job(paths: &Paths) -> Result<Job, Error> {
    job(
        paths,
        &user_home()?,
        Path::new("/usr/bin/pkg"),
        Path::new("/usr/bin/nix"),
        cfg!(target_os = "macos"),
    )
}

pub fn disable(paths: &Paths) -> Result<(), Error> {
    let job = configured_job(paths)?;
    let present = job
        .files
        .iter()
        .map(|(path, _)| owned(path))
        .collect::<Result<Vec<_>, _>>()?;
    if !present.iter().any(|present| *present) {
        return Ok(());
    }
    // Without a user manager no schedule runs, so only the files remain.
    let scheduler = scheduler_ready()?;
    if cfg!(target_os = "macos") {
        let target = format!("{}/{LABEL}", domain());
        control("/bin/launchctl", &["disable", &target])?;
        optional_control("/bin/launchctl", &["bootout", &target])?;
    } else if scheduler {
        control(
            "systemctl",
            &["--user", "disable", "--now", "pkg-catalog-refresh.timer"],
        )?;
    }
    for ((path, _), present) in job.files.iter().zip(present) {
        if present {
            std::fs::remove_file(path)?;
        }
    }
    if !cfg!(target_os = "macos") && scheduler {
        control("systemctl", &["--user", "daemon-reload"])?;
    }
    Ok(())
}

/// Whether the scheduled user job is enabled.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum State {
    /// Job files exist and the schedule is active.
    On,
    /// No pkg-owned job files exist.
    Off,
    /// The system cannot run the job.
    Unavailable,
}

/// Read the job state without changing it.
pub fn state(paths: &Paths) -> Result<State, Error> {
    let job = configured_job(paths)?;
    if !job
        .files
        .iter()
        .map(|(path, _)| owned(path))
        .collect::<Result<Vec<_>, _>>()?
        .iter()
        .all(|present| *present)
    {
        return Ok(if scheduler_ready()? {
            State::Off
        } else {
            State::Unavailable
        });
    }
    let result = if cfg!(target_os = "macos") {
        control(
            "/bin/launchctl",
            &["print", &format!("{}/{LABEL}", domain())],
        )
    } else {
        control(
            "systemctl",
            &["--user", "is-active", "pkg-catalog-refresh.timer"],
        )
    };
    result
        .map(|()| State::On)
        .map_err(|error| Error::Schedule(Box::new(error)))
}

/// Why the job cannot run here, and what to do instead.
#[must_use]
pub fn unavailable_detail() -> String {
    format!("this system has no systemd user session. {MANUAL}")
}

pub fn status(paths: &Paths) -> Result<String, Error> {
    let log = if cfg!(target_os = "macos") {
        configured_job(paths)?.log.display().to_string()
    } else {
        String::from("journalctl --user -u pkg-catalog-refresh.service")
    };
    Ok(match state(paths)? {
        State::On => format!("On: pkg and its search data update daily.\nLog: {log}"),
        State::Off => String::from("Off: pkg and its search data do not update."),
        State::Unavailable => format!("Off: {}", unavailable_detail()),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn job_preserves_paths_and_runs_only_the_scheduled_update() {
        let root = Path::new("/tmp/pkg spaces % $ & ' \\");
        let paths = Paths::from_bases(
            &root.join("state"),
            &root.join("config"),
            &root.join("cache"),
        );
        for macos in [true, false] {
            let job = job(
                &paths,
                root,
                &root.join("bin/pkg"),
                Path::new("/nix/profile/bin/nix"),
                macos,
            )
            .expect("job");
            assert!(job.files[0].1.contains("--scheduled"));
            if macos {
                #[cfg(target_os = "macos")]
                {
                    let temporary = tempfile::tempdir().expect("directory");
                    let plist = temporary.path().join("job.plist");
                    std::fs::write(&plist, &job.files[0].1).expect("write plist");
                    let output = std::process::Command::new("/usr/bin/plutil")
                        .arg("-lint")
                        .arg(&plist)
                        .output()
                        .expect("plutil");
                    assert!(
                        output.status.success(),
                        "{}",
                        String::from_utf8_lossy(&output.stdout)
                    );
                }
                assert!(job.files[0].1.contains("&amp;"));
                assert!(!job.files[0].1.contains("KeepAlive"));
            } else {
                assert!(job.files[0].1.contains("%% $$"));
                assert!(job.files[1].1.contains("OnUnitInactiveSec=1d"));
            }
        }
        let directory = tempfile::tempdir().expect("directory");
        let file = directory.path().join("job");
        std::fs::write(&file, "user content").expect("write");
        assert!(owned(&file).is_err());
        assert_eq!(
            std::fs::read_to_string(&file).expect("read"),
            "user content"
        );
    }

    #[test]
    fn optional_control_retains_cancellation_and_tolerates_ordinary_failure() {
        for name in ["INT", "TERM", "HUP"] {
            let error =
                optional_control("/bin/sh", &["-c", &format!("kill -{name} $$")]).unwrap_err();
            let signal = match name {
                "INT" => libc::SIGINT,
                "TERM" => libc::SIGTERM,
                "HUP" => libc::SIGHUP,
                _ => unreachable!(),
            };
            assert_eq!(error.signal(), Some(signal));
        }
        assert!(optional_control("/bin/sh", &["-c", "exit 9"]).is_ok());
    }
}
