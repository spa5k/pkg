//! Per-user periodic jobs for official discovery metadata.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::config::Paths;

const LABEL: &str = "com.pkg.catalog-refresh";
const MARKER: &str = "Generated by pkg; catalog refresh only.";

struct Job {
    files: Vec<(PathBuf, String)>,
    log: PathBuf,
}

fn text(path: &Path) -> Result<&str, String> {
    let value = path.to_str().ok_or("job paths must be UTF-8")?;
    if value.chars().any(char::is_control) {
        return Err(String::from(
            "job paths must not contain control characters",
        ));
    }
    Ok(value)
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn unit(value: &str, exec: bool) -> String {
    let value = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    format!(
        "\"{}\"",
        if exec {
            value.replace('$', "$$")
        } else {
            value
        }
    )
}

fn user_home() -> Result<PathBuf, String> {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .ok_or_else(|| String::from("HOME must be absolute for background setup"))
}

fn job(
    paths: &Paths,
    home: &Path,
    executable: &Path,
    nix: &Path,
    macos: bool,
) -> Result<Job, String> {
    let executable = text(executable)?;
    let state = text(&paths.state_home)?;
    let config_base = paths
        .config_file
        .parent()
        .and_then(Path::parent)
        .ok_or("config base is missing")?;
    let config = text(config_base)?;
    let cache_base = paths.cache_dir.parent().ok_or("cache base is missing")?;
    let cache = text(cache_base)?;
    let home_text = text(home)?;
    let nix_bin = text(nix.parent().ok_or("Nix executable has no parent")?)?;
    let inherited_path = std::env::var("PATH").unwrap_or_default();
    if inherited_path.chars().any(char::is_control) {
        return Err(String::from(
            "PATH must not contain control characters for background setup",
        ));
    }
    let path = format!("{nix_bin}:{inherited_path}:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin");
    let log = paths.state_home.join("pkg/catalog-refresh.log");
    let log_text = text(&log)?;
    let environment = [
        ("HOME", home_text),
        ("XDG_STATE_HOME", state),
        ("XDG_CONFIG_HOME", config),
        ("XDG_CACHE_HOME", cache),
        ("PATH", path.as_str()),
    ];
    let files = if macos {
        let mut env = String::new();
        for (key, value) in &environment {
            let _ = write!(env, "<key>{key}</key><string>{}</string>", xml(value));
        }
        let content = format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<!-- {MARKER} -->\n<plist version=\"1.0\"><dict>\n<key>Label</key><string>{LABEL}</string>\n<key>ProgramArguments</key><array><string>{}</string><string>update</string><string>--catalogs-only</string></array>\n<key>EnvironmentVariables</key><dict>{env}</dict>\n<key>StartInterval</key><integer>86400</integer>\n<key>ProcessType</key><string>Background</string>\n<key>Nice</key><integer>10</integer>\n<key>LowPriorityIO</key><true/>\n<key>StandardInPath</key><string>/dev/null</string>\n<key>StandardOutPath</key><string>{}</string>\n<key>StandardErrorPath</key><string>{}</string>\n</dict></plist>\n",
            xml(executable),
            xml(log_text),
            xml(log_text)
        );
        vec![(
            home.join(format!("Library/LaunchAgents/{LABEL}.plist")),
            content,
        )]
    } else {
        let mut env = String::new();
        for (key, value) in &environment {
            let _ = writeln!(
                env,
                "Environment={}",
                unit(&format!("{key}={value}"), false)
            );
        }
        let service = format!(
            "# {MARKER}\n[Unit]\nDescription=Refresh pkg package catalogs\n[Service]\nType=oneshot\nExecStart={} update --catalogs-only\n{env}StandardInput=null\nNice=10\nTimeoutStartSec=30min\n",
            unit(executable, true)
        );
        let timer = format!(
            "# {MARKER}\n[Unit]\nDescription=Daily pkg catalog refresh\n[Timer]\nOnStartupSec=10min\nOnUnitInactiveSec=1d\nRandomizedDelaySec=10min\n[Install]\nWantedBy=timers.target\n"
        );
        let directory = config_base.join("systemd/user");
        vec![
            (directory.join("pkg-catalog-refresh.service"), service),
            (directory.join("pkg-catalog-refresh.timer"), timer),
        ]
    };
    Ok(Job { files, log })
}

fn owned(path: &Path) -> Result<bool, String> {
    match std::fs::symlink_metadata(path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error.to_string()),
        Ok(metadata) if metadata.is_file() && !metadata.file_type().is_symlink() => {
            let content = std::fs::read_to_string(path).map_err(|error| error.to_string())?;
            if content.contains(MARKER) {
                Ok(true)
            } else {
                Err(format!(
                    "refusing to replace a job file not owned by pkg: {}",
                    path.display()
                ))
            }
        }
        Ok(_) => Err(format!("unsafe job file: {}", path.display())),
    }
}

fn write(path: &Path, content: &str) -> Result<(), String> {
    use std::io::Write as _;
    let directory = path.parent().ok_or("job directory is missing")?;
    std::fs::create_dir_all(directory).map_err(|error| error.to_string())?;
    let mut file = tempfile::NamedTempFile::new_in(directory).map_err(|error| error.to_string())?;
    file.write_all(content.as_bytes())
        .and_then(|()| file.as_file().sync_all())
        .map_err(|error| error.to_string())?;
    file.persist(path).map_err(|error| error.to_string())?;
    Ok(())
}

fn control(program: &str, args: &[&str]) -> Result<(), String> {
    let args: Vec<String> = args.iter().map(|arg| (*arg).to_string()).collect();
    match crate::nix::run_direct(Path::new(program), &args)? {
        crate::nix::Outcome::Success => Ok(()),
        crate::nix::Outcome::Failed { status, stderr } => Err(format!(
            "{program} {}: {status}: {}",
            args.join(" "),
            stderr.trim()
        )),
        crate::nix::Outcome::Interrupted { signal } => {
            Err(format!("{program} was cancelled by signal {signal}"))
        }
    }
}

fn domain() -> String {
    // SAFETY: geteuid has no arguments or memory effects.
    format!("gui/{}", unsafe { libc::geteuid() })
}

pub fn enable(paths: &Paths, nix: &Path) -> Result<(), String> {
    let executable = std::env::current_exe().map_err(|error| error.to_string())?;
    let job = job(
        paths,
        &user_home()?,
        &executable,
        nix,
        cfg!(target_os = "macos"),
    )?;
    for (path, _) in &job.files {
        owned(path)?;
    }
    for (path, content) in &job.files {
        write(path, content)?;
    }
    if cfg!(target_os = "macos") {
        if let Some(parent) = job.log.parent() {
            std::fs::create_dir_all(parent).map_err(|error| error.to_string())?;
        }
        let target = format!("{}/{LABEL}", domain());
        let _ = control("/bin/launchctl", &["bootout", &target]);
        control("/bin/launchctl", &["enable", &target])?;
        control(
            "/bin/launchctl",
            &["bootstrap", &domain(), text(&job.files[0].0)?],
        )?;
        println!("Refresh log: {}", job.log.display());
    } else {
        control("systemctl", &["--user", "daemon-reload"])?;
        control(
            "systemctl",
            &["--user", "enable", "--now", "pkg-catalog-refresh.timer"],
        )?;
        println!("Refresh log: journalctl --user -u pkg-catalog-refresh.service");
    }
    Ok(())
}

fn configured_job(paths: &Paths) -> Result<Job, String> {
    job(
        paths,
        &user_home()?,
        Path::new("/usr/bin/pkg"),
        Path::new("/usr/bin/nix"),
        cfg!(target_os = "macos"),
    )
}

pub fn disable(paths: &Paths) -> Result<(), String> {
    let job = configured_job(paths)?;
    let present = job
        .files
        .iter()
        .map(|(path, _)| owned(path))
        .collect::<Result<Vec<_>, _>>()?;
    if !present.iter().any(|present| *present) {
        return Ok(());
    }
    if cfg!(target_os = "macos") {
        let target = format!("{}/{LABEL}", domain());
        control("/bin/launchctl", &["disable", &target])?;
        let _ = control("/bin/launchctl", &["bootout", &target]);
    } else {
        control(
            "systemctl",
            &["--user", "disable", "--now", "pkg-catalog-refresh.timer"],
        )?;
    }
    for ((path, _), present) in job.files.iter().zip(present) {
        if present {
            std::fs::remove_file(path).map_err(|error| error.to_string())?;
        }
    }
    if !cfg!(target_os = "macos") {
        control("systemctl", &["--user", "daemon-reload"])?;
    }
    Ok(())
}

pub fn status(paths: &Paths) -> Result<String, String> {
    let job = configured_job(paths)?;
    if !job
        .files
        .iter()
        .map(|(path, _)| owned(path))
        .collect::<Result<Vec<_>, _>>()?
        .iter()
        .all(|present| *present)
    {
        return Ok(String::from(
            "Disabled: daily catalog refresh. Enable it with `pkg background enable`.",
        ));
    }
    let result = if cfg!(target_os = "macos") {
        control(
            "/bin/launchctl",
            &["print", &format!("{}/{LABEL}", domain())],
        )
    } else {
        control(
            "systemctl",
            &["--user", "is-active", "pkg-catalog-refresh.timer"],
        )
    };
    result.map(|()| String::from("Enabled: daily official catalog refresh.")).map_err(|error| format!("job files exist, but the schedule is not active: {error}. Run `pkg background enable`."))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn job_preserves_paths_and_runs_only_catalog_refresh() {
        let root = Path::new("/tmp/pkg spaces % $ & ' \\");
        let paths = Paths::from_bases(
            &root.join("state"),
            &root.join("config"),
            &root.join("cache"),
        );
        for macos in [true, false] {
            let job = job(
                &paths,
                root,
                &root.join("bin/pkg"),
                Path::new("/nix/profile/bin/nix"),
                macos,
            )
            .expect("job");
            assert!(job.files[0].1.contains("--catalogs-only"));
            if macos {
                #[cfg(target_os = "macos")]
                {
                    let temporary = tempfile::tempdir().expect("directory");
                    let plist = temporary.path().join("job.plist");
                    std::fs::write(&plist, &job.files[0].1).expect("write plist");
                    let output = std::process::Command::new("/usr/bin/plutil")
                        .arg("-lint")
                        .arg(&plist)
                        .output()
                        .expect("plutil");
                    assert!(
                        output.status.success(),
                        "{}",
                        String::from_utf8_lossy(&output.stdout)
                    );
                }
                assert!(job.files[0].1.contains("&amp;"));
                assert!(!job.files[0].1.contains("KeepAlive"));
            } else {
                assert!(job.files[0].1.contains("%% $$"));
                assert!(job.files[1].1.contains("OnUnitInactiveSec=1d"));
            }
        }
        let directory = tempfile::tempdir().expect("directory");
        let file = directory.path().join("job");
        std::fs::write(&file, "user content").expect("write");
        assert!(owned(&file).is_err());
        assert_eq!(
            std::fs::read_to_string(&file).expect("read"),
            "user content"
        );
    }
}
